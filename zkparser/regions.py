def resolve_region(value: str) -> str:
    """The 11-digit code of a region given as a code (``72``, ``72000000000``) or part of its name (``тюмен``)."""
    value = value.strip()
    if value.isdigit():
        code = value.zfill(2).ljust(11, "0") if len(value) <= 2 else value
        if code in REGIONS:
            return code
        raise ValueError(f"Нет региона с кодом {value}. Список регионов: python -m zkparser regions")
    needle = value.casefold()
    matches = [code for code, name in REGIONS.items() if needle in name.casefold()]
    if len(matches) == 1:
        return matches[0]
    if not matches:
        raise ValueError(f"Не найден регион «{value}». Список регионов: python -m zkparser regions")
    names = ", ".join(REGIONS[code] for code in matches[:5])
    raise ValueError(f"«{value}» подходит к нескольким регионам: {names}. Уточните название или укажите код.")
